"""Evaluation result types and JSON serialization.

These are the output contract of every eval run. ``results.json`` is written
by ``EvalController.run()`` and read by the Streamlit dashboard and CI gates.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from pathlib import Path


@dataclass
class ToolCall:
    """A single tool invocation recorded during a MAF agent run."""

    turn: int
    tool_name: str
    arguments: dict[str, object]
    response: dict[str, object]


@dataclass
class AgentResponse:
    """The result of a single end-to-end MAF agent run."""

    content: str
    trajectory: list[ToolCall] = field(default_factory=list)
    prompt_tokens: int = 0
    completion_tokens: int = 0


@dataclass
class CaseResult:
    """Result of a single test case evaluation.

    Parameters
    ----------
    case_id:   Unique case identifier (e.g. ``"TC-001"``).
    agent:     Agent name that ran this case.
    category:  Evaluation category (functional, safety, privacy, equity, operational).
    input_summary: First 120 chars of the patient's opening message.
    score:     Judge score 0.0–1.0.
    passed:    True when ``score >= threshold`` for this category.
    rationale: Human-readable explanation from the judge.
    trajectory: Serialized tool-call trajectory from the eval run.
    latency_ms: Wall-clock time for the agent run in milliseconds.
    prompt_tokens:     Tokens consumed by the agent (prompt side).
    completion_tokens: Tokens generated by the agent (completion side).
    metadata:  Demographic metadata from the test case (for equity analysis).
    """

    case_id: str
    agent: str
    category: str
    input_summary: str
    score: float
    passed: bool
    rationale: str
    trajectory: list[dict[str, object]]
    latency_ms: float
    prompt_tokens: int
    completion_tokens: int
    metadata: dict[str, object] = field(default_factory=dict)


@dataclass
class CategorySummary:
    """Aggregate pass/fail summary for one evaluation category.

    Parameters
    ----------
    category:       Category name.
    total:          Total cases in this category.
    passed_count:   Cases where ``score >= threshold``.
    pass_rate:      ``passed_count / total`` (0.0–1.0).
    threshold:      The required pass rate to meet the gate.
    met_threshold:  True when ``pass_rate >= threshold``.
    """

    category: str
    total: int
    passed_count: int
    pass_rate: float
    threshold: float
    met_threshold: bool


@dataclass
class EvalResults:
    """Complete results of one eval run, ready for ``results.json`` and the dashboard.

    Parameters
    ----------
    agent:      Agent name evaluated.
    run_at:     ISO 8601 UTC timestamp of the run.
    cases:      Per-case results in execution order.
    categories: Per-category summaries and threshold decisions.
    passed:     True only when every category meets its threshold.
    """

    agent: str
    run_at: str
    cases: list[CaseResult]
    categories: list[CategorySummary]
    passed: bool

    @classmethod
    def create(
        cls,
        agent: str,
        cases: list[CaseResult],
        categories: list[CategorySummary],
    ) -> EvalResults:
        """Construct with auto-populated ``run_at`` timestamp."""
        return cls(
            agent=agent,
            run_at=datetime.now(UTC).isoformat(),
            cases=cases,
            categories=categories,
            passed=all(c.met_threshold for c in categories),
        )

    def to_dict(self) -> dict[str, object]:
        """Serialize to a JSON-compatible dict."""
        return {
            "agent": self.agent,
            "run_at": self.run_at,
            "passed": self.passed,
            "categories": [asdict(c) for c in self.categories],
            "cases": [asdict(c) for c in self.cases],
        }

    def write_json(self, path: Path) -> None:
        """Write ``results.json`` to ``path``, creating parent directories if needed."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.to_dict(), indent=2), encoding="utf-8")
